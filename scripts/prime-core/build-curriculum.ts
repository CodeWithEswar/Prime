async function main() {
  const catalogCache: Record<string, { id: string; slug: string; title: string; difficulty: string }> =
    JSON.parse(fs.readFileSync("data/prime-core/catalog-cache.json", "utf8"));

  console.log(`Checking ${CURRICULUM_CANDIDATES.length} candidate entries against 4,411 catalog problems...`);

  const seenSlugs = new Set<string>();
  const validatedList: Array<RawCurriculumEntry & { problemId: string; title: string; difficulty: string }> = [];
  const missingSlugs: string[] = [];

  let seq = 1;
  for (const entry of CURRICULUM_CANDIDATES) {
    if (seenSlugs.has(entry.slug)) {
      console.log(`Duplicate candidate in list: ${entry.slug}, skipping duplicate.`);
      continue;
    }

    const matched = catalogCache[entry.slug.toLowerCase()];
    if (!matched) {
      missingSlugs.push(entry.slug);
      console.warn(`WARNING: Candidate slug not in catalog: "${entry.slug}"`);
      continue;
    }

    seenSlugs.add(entry.slug);
    validatedList.push({
      ...entry,
      problemId: matched.id,
      title: matched.title,
      difficulty: matched.difficulty.toUpperCase(),
    });
    seq++;
  }

  console.log(`\nValidated ${validatedList.length} unique problems.`);
  if (missingSlugs.length > 0) {
    console.error(`Missing slugs (${missingSlugs.length}):`, missingSlugs);
  }

  const difficultyCounts: Record<string, number> = {};
  const stageCounts: Record<string, number> = {};
  for (const item of validatedList) {
    difficultyCounts[item.difficulty] = (difficultyCounts[item.difficulty] || 0) + 1;
    stageCounts[item.stageSlug] = (stageCounts[item.stageSlug] || 0) + 1;
  }

  console.log("\nDifficulty Distribution:", difficultyCounts);
  console.log("Stage Distribution:", stageCounts);

  const fileContent = `/**
 * PRIME Core DSA Curriculum Seed (V1 - 2026.1)
 * Exactly ${validatedList.length} canonical high-value DSA problems curated across 16 stages.
 * Automatically generated & validated against the 4,411 canonical catalog.
 */

export interface CurriculumSeedItem {
  slug: string;
  stageSlug: string;
  sequence: number;
  priority: "P0" | "P1" | "P2";
  recommendedMinutes: number;
  isRequired: boolean;
  isCheckpoint: boolean;
  selectionReason: string;
}

export const PRIME_CORE_SEED_ITEMS: CurriculumSeedItem[] = ${JSON.stringify(
    validatedList.map((item, idx) => ({
      slug: item.slug,
      stageSlug: item.stageSlug,
      sequence: idx + 1,
      priority: item.priority,
      recommendedMinutes: item.recommendedMinutes,
      isRequired: item.isRequired,
      isCheckpoint: Boolean(item.isCheckpoint),
      selectionReason: item.selectionReason,
    })),
    null,
    2
  )};
`;

  fs.writeFileSync("data/prime-core/curriculum.ts", fileContent, "utf8");
  console.log("\nSuccessfully generated data/prime-core/curriculum.ts!");
}

main().catch(console.error);
