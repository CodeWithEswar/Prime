import "server-only";
import type { ContextRef } from "@/features/ai/schema";
import type { AIContext } from "@/features/ai/types";
import { AIError } from "@/lib/ai/errors";
import { loadAlgorithm } from "../registry/registry";
import { algorithmMetadata, ALGORITHMS } from "../registry/metadata";
import { parseInputJSON } from "../engine/input";
export async function loadLabAIContext(ref: ContextRef): Promise<AIContext> {
  if (!ref.ref)
    return {
      reference: ref,
      label: "Algorithm Lab",
      subtitle: "Deterministic visual learning",
      facts: {
        availableAlgorithms: ALGORITHMS.map((a) => ({ slug: a.slug, name: a.name })),
        authority:
          "Lab activity is separate from Mastery. Ask which algorithm the learner wants to explore.",
      },
      references: [{ title: "Algorithm Lab", href: "/lab" }],
      unavailable: [],
    };
  const metadata = algorithmMetadata(ref.ref);
  if (!metadata)
    throw new AIError("NOT_FOUND", "Choose an available Lab algorithm.", 404);
  try {
    const algorithm = await loadAlgorithm(ref.ref),
      input = ref.lab ? parseInputJSON(ref.lab.input) : algorithm.defaultInput,
      trace = algorithm.generateTrace(input),
      index = ref.lab?.step ?? 0;
    if (index >= trace.steps.length)
      throw new Error("The requested step is outside this trace.");
    const step = trace.steps[index],
      line = algorithm.java.lines.find((line) => line.id === step.code);
    const facts = {
      algorithm: metadata.name,
      algorithmId: trace.algorithmId,
      mode: ref.lab?.mode ?? "step",
      input: trace.input,
      currentStep: index + 1,
      totalSteps: trace.steps.length,
      operation: step.operation,
      state: step.scene,
      variables: step.variables,
      metrics: step.metrics,
      activeJavaLine: line,
      explanation: step.explanation,
      invariant: algorithm.invariant,
      complexity: algorithm.complexity,
      authority:
        "This snapshot was regenerated by the trusted trace engine. Explain it; never choose or mutate the next execution step, claim a Lab result is Mastery evidence, or mark an attempt/revision complete.",
    };
    return {
      reference: ref,
      label: metadata.name,
      subtitle: `Algorithm Lab · step ${index + 1} of ${trace.steps.length} · attached snapshot`,
      facts,
      references: [{ title: `${metadata.name} Lab`, href: `/lab/${metadata.slug}` }],
      unavailable: [],
    };
  } catch (error) {
    if (error instanceof AIError) throw error;
    throw new AIError(
      "INVALID_REQUEST",
      "This Lab input or step is invalid. Regenerate the trace and attach it again.",
      400
    );
  }
}
